def render_sitemap(records: list[dict[str, Any]]) -> str:
    articles = public_articles(records)
    urls: list[tuple[str, str]] = [
        (SITE_URL + "/", max((safe_date(a.get("date")) for a in articles), default="")),
        (SITE_URL + "/analytics.html", max((safe_date(a.get("date")) for a in articles), default="")),
        (SITE_URL + "/action-lab.html", ""),
    ]
    for article in articles:
        modified = safe_date(article.get("editorialReviewedAt")) or safe_date(article.get("date") or article.get("sourceDate"))
        urls.append((article_url(article), modified))

    seen: set[str] = set()
    entries = []
    for url, lastmod in urls:
        if url in seen:
            raise ValueError(f"Duplicate canonical URL in sitemap: {url}")
        seen.add(url)
        entries.append(
            "  <url>\n"
            f"    <loc>{xml_escape(url)}</loc>\n"
            + (f"    <lastmod>{xml_escape(lastmod)}</lastmod>\n" if lastmod else "")
            + "  </url>"
        )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(entries) + "\n</urlset>\n"
    )


def render_robots() -> str:
    return (
        "User-agent: *\n"
        "Allow: /\n"
        f"Sitemap: {SITE_URL}/sitemap.xml\n"
    )


def related_for(article: dict[str, Any], articles: list[dict[str, Any]]) -> list[dict[str, Any]]:
    same_category = [
        item for item in articles
        if item.get("id") != article.get("id") and item.get("category") == article.get("category")
    ]
    same_category.sort(key=lambda item: safe_date(item.get("date")), reverse=True)
    if len(same_category) < 3:
        seen = {item.get("id") for item in same_category} | {article.get("id")}
        others = [item for item in articles if item.get("id") not in seen]
        others.sort(key=lambda item: safe_date(item.get("date")), reverse=True)
        same_category.extend(others[: 3 - len(same_category)])
    return same_category[:3]


def build_outputs(records: list[dict[str, Any]]) -> dict[str, str]:
    articles = public_articles(records)
    seen_slugs: set[str] = set()
    outputs: dict[str, str] = {}
    for article in articles:
        slug = article_slug(article)
        if slug in seen_slugs:
            raise ValueError(f"Duplicate article slug: {slug}")
        seen_slugs.add(slug)
        outputs[f"articles/{slug}/index.html"] = render_article_page(
            article, related_for(article, articles)
        )
    outputs["sitemap.xml"] = render_sitemap(records)
    outputs["robots.txt"] = render_robots()
    return outputs


def write_outputs(outputs: dict[str, str]) -> None:
    expected = set(outputs)
    ARTICLE_ROOT.mkdir(parents=True, exist_ok=True)
    for current in ARTICLE_ROOT.rglob("index.html"):
        try:
            content = current.read_text(encoding="utf-8")
        except OSError:
            continue
        if GENERATOR_MARKER in content and current.relative_to(ROOT).as_posix() not in expected:
            current.unlink()
    for relative, content in outputs.items():
        target = ROOT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
    for directory in sorted((p for p in ARTICLE_ROOT.rglob("*") if p.is_dir()), reverse=True):
        try:
            directory.rmdir()
        except OSError:
            pass


def check_outputs(outputs: dict[str, str]) -> list[str]:
    problems: list[str] = []
    expected = set(outputs)
    for relative, expected_content in outputs.items():
        target = ROOT / relative
        if not target.exists():
            problems.append(f"Відсутній файл: {relative}")
            continue
        actual = target.read_text(encoding="utf-8")
        if actual != expected_content:
            problems.append(f"Файл не відповідає бібліотеці: {relative}")
    if ARTICLE_ROOT.exists():
        for current in ARTICLE_ROOT.rglob("index.html"):
            actual = current.read_text(encoding="utf-8")
            relative = current.relative_to(ROOT).as_posix()
            if GENERATOR_MARKER in actual and relative not in expected:
                problems.append(f"Застаріла згенерована сторінка: {relative}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Перевірити, чи сторінки та sitemap відповідають бібліотеці.")
    mode.add_argument("--write", action="store_true", help="Згенерувати HTML-сторінки, sitemap.xml і robots.txt.")
    args = parser.parse_args()

    if not ARTICLES_FILE.exists():
        print(f"Не знайдено бібліотеку: {ARTICLES_FILE}", file=sys.stderr)
        return 1

    try:
        records = json.loads(ARTICLES_FILE.read_text(encoding="utf-8"))
        if not isinstance(records, list):
            raise ValueError("content/articles.json має бути масивом.")
        outputs = build_outputs(records)
        if args.check:
            problems = check_outputs(outputs)
            if problems:
                for problem in problems:
                    print(f"[SEO CHECK] {problem}", file=sys.stderr)
                return 1
            print(f"[SEO CHECK] OK: {len(public_articles(records))} сторінок матеріалів, sitemap.xml і robots.txt актуальні.")
            return 0

        write_outputs(outputs)
        print(f"[SEO BUILD] Створено/оновлено {len(public_articles(records))} сторінок матеріалів, sitemap.xml і robots.txt.")
        return 0
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"[SEO BUILD] Помилка: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
