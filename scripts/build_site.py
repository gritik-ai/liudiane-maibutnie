def plain_text(value: Any) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def safe_date(value: Any) -> str:
    match = re.match(r"^(\d{4}-\d{2}-\d{2})", str(value or ""))
    return match.group(1) if match else ""


def is_public_article(article: dict[str, Any]) -> bool:
    """Mirror the public-article filter used by index.html and analytics.html."""
    return not article.get("autoPublished") or article.get("editorialStatus") == "approved"


def public_articles(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [
        article for article in records
        if isinstance(article, dict)
        and plain_text(article.get("id"))
        and plain_text(article.get("title"))
        and is_public_article(article)
    ]


def article_slug(article: dict[str, Any]) -> str:
    title = plain_text(article.get("title")).lower().translate(TRANSLITERATION)
    title = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode("ascii")
    base = re.sub(r"[^a-z0-9]+", "-", title).strip("-")[:72].rstrip("-")
    suffix = re.sub(r"[^a-z0-9]+", "-", plain_text(article.get("id")).lower()).strip("-")[-12:]
    return f"{base or 'material'}-{suffix or 'item'}"


def article_url(article: dict[str, Any]) -> str:
    return f"{SITE_URL}/articles/{article_slug(article)}/"


def xml_escape(value: Any) -> str:
    return html.escape(str(value or ""), quote=True)


def json_for_script(value: Any) -> str:
    return (
        json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        .replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
    )


def shorten(value: Any, limit: int = 160) -> str:
    text = plain_text(value)
    if len(text) <= limit:
        return text
    shortened = text[: limit - 1].rsplit(" ", 1)[0].rstrip(" ,;:-")
    return (shortened or text[: limit - 1]).rstrip() + "…"


def safe_source_url(value: Any) -> str:
    candidate = plain_text(value)
    try:
        parsed = urlsplit(candidate)
    except ValueError:
        return ""
    if parsed.scheme != "https" or not parsed.hostname:
        return ""
    return candidate


def render_body(body: Any) -> str:
    text = str(body or "").strip()
    if not text:
        return ""
    paragraphs = re.split(r"\n\s*\n", text)
    rendered = []
    for paragraph in paragraphs:
        clean = paragraph.strip()
        if clean:
            rendered.append(f"<p>{html.escape(clean).replace(chr(10), '<br>')}</p>")
    return "\n".join(rendered)


def render_sources(article: dict[str, Any]) -> str:
    sources = article.get("sources")
    if not isinstance(sources, list):
        return ""
    items = []
    for source in sources:
        if not isinstance(source, dict):
            continue
        url = safe_source_url(source.get("url"))
        if not url:
            continue
        title = plain_text(source.get("title")) or "Відкрити першоджерело"
        publisher = plain_text(source.get("publisher"))
        label = f"{title} — {publisher}" if publisher else title
        items.append(
            '<li><a href="' + html.escape(url, quote=True)
            + '" target="_blank" rel="noopener noreferrer">'
            + html.escape(label) + "</a></li>"
        )
    if not items:
        return ""
    return '<section class="sources" aria-labelledby="sources-title"><h2 id="sources-title">Першоджерела</h2><ul>' + "".join(items) + "</ul></section>"


def render_related(article: dict[str, Any], related: list[dict[str, Any]]) -> str:
    if not related:
        return ""
    cards = []
    for item in related:
        cards.append(
            '<li><a href="' + html.escape(article_url(item), quote=True) + '">'
            + html.escape(plain_text(item.get("title"))) + "</a></li>"
        )
    return (
        '<aside class="related" aria-labelledby="related-title">'
        '<h2 id="related-title">Читайте також</h2><ul>'
        + "".join(cards) + "</ul></aside>"
    )



